StateFreezeAttackHold::StateFreezeAttackHold(Boss* boss, u32 frame)
    : StateBase(boss), mFrame(frame), mCount(0), mShakeWait(0) {
    Custom& custom = hel::common::DynamicCastToRef<Custom, ICustom>(obj().custom());
    custom.collisionCtrl().setState(CollisionCtrl::STATE_1);
    obj().model().reqScript(0x20);
    obj().model().rotCtrl().setRotHTarget(0.0f);
    obj().guard().setType(static_cast<GuardType>(4));
}

StateFreezeAttackHold::~StateFreezeAttackHold() {}

void StateFreezeAttackHold::procAnim() {
    if (mCount < mFrame) {
        mCount++;
    } else {
        obj().stateChanger().setNextState<StateFreezeAttack, Boss*>(objPtr());
    }
    if (mCount > mFrame / 2) {
        if (mShakeWait != 0) {
            mShakeWait--;
        } else {
            mShakeWait = 4;
            obj().model().shake().request(static_cast<chara::ShakeKind>(2));
        }
    }
}

void StateFreezeAttackHold::procMove() {}

void StateFreezeAttackHold::procFixPos() {}

